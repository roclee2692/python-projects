import re


def count_words_strict(text):
    """
    统计字数：
    1. 中文：每个汉字算 1 个字。
    2. 英文/数字：连续的字母或数字算 1 个单词。
    3. 严格剔除：空格、换行、所有标点符号（中英文）。
    """

    # 1. 统计中文字符
    # 使用正则表达式匹配所有汉字 (范围 \u4e00-\u9fa5)
    # 这会自动排除中文标点（如 ，。！等）
    chinese_chars = re.findall(r'[\u4e00-\u9fa5]', text)
    count_zh = len(chinese_chars)

    # 2. 统计英文单词和数字
    # 先把中文替换为空格，避免干扰
    text_no_chinese = re.sub(r'[\u4e00-\u9fa5]', ' ', text)

    # 使用正则表达式匹配连续的字母或数字序列
    # r'[a-zA-Z0-9]+' 会把 "hello" 算作一个，把 "123" 算作一个
    # 标点符号会自然成为分隔符而被忽略
    english_words = re.findall(r'[a-zA-Z0-9]+', text_no_chinese)
    count_en = len(english_words)

    # 3. 计算总数
    total_count = count_zh + count_en

    return {
        "total": total_count,
        "chinese": count_zh,
        "english": count_en
    }


